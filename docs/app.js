/* Virginia PI Templates - offline browser. No build step, no network calls.
   Data comes from data.js (window.VPT_DATA), generated by scripts/build_index.py.
   The fill logic mirrors scripts/fill_template.py (same keys: NAME, NAME@context, NAME#n). */
(function () {
  "use strict";

  var DATA = window.VPT_DATA || { templates: [], routes: [], categories: [] };
  var REPO_URL = "https://github.com/kvngnsn/virginia-pi-templates/blob/main/";
  var FIELD_RE = /\[([^\[\]\n]+)\]/g;
  var LAYOUTS = {
    COURT: "Court paper (double-spaced, caption)",
    LETTER: "Letter (single-spaced block format)",
    DOCUMENT: "Plain document (single-spaced)",
    APPELLATE: "Appellate brief (14 pt, cover, front matter, body)",
    APPELLATE_PAPER: "Appellate paper (14 pt, no cover)"
  };

  var $ = function (id) { return document.getElementById(id); };
  var state = { current: null, values: {} };

  // ------------------------------------------------------------------ helpers
  function el(tag, attrs, children) {
    var node = document.createElement(tag);
    if (attrs) Object.keys(attrs).forEach(function (k) {
      if (k === "text") node.textContent = attrs[k];
      else if (k === "class") node.className = attrs[k];
      else node.setAttribute(k, attrs[k]);
    });
    (children || []).forEach(function (c) { if (c != null) node.appendChild(typeof c === "string" ? document.createTextNode(c) : c); });
    return node;
  }
  function body(t) {
    var md = t.md || "";
    if (md.indexOf("---\n") !== 0) return md;
    var end = md.indexOf("\n---\n", 4);
    return end === -1 ? md : md.slice(end + 5);
  }
  function normName(s) { return s.replace(/^\[|\]$/g, "").trim().replace(/\s+/g, " ").toLowerCase(); }
  var LEFT = "([{\"'“‘";
  function contextOf(line, start) {
    var before = line.slice(0, start);
    var cut = before.lastIndexOf("]");
    if (cut !== -1) before = before.slice(cut + 1);
    var toks = before.trim().split(/\s+/).filter(Boolean);
    if (!toks.length) return "";
    var tok = toks[toks.length - 1];
    var i = 0;
    while (i < tok.length && LEFT.indexOf(tok[i]) !== -1) i++;
    return tok.slice(i);
  }
  function findFields(text) {
    var out = [], seen = {};
    text.split("\n").forEach(function (line, idx) {
      var m; FIELD_RE.lastIndex = 0;
      while ((m = FIELD_RE.exec(line))) {
        var key = normName(m[1]);
        seen[key] = (seen[key] || 0) + 1;
        out.push({ name: m[1], key: key, occurrence: seen[key], line: idx, start: m.index, end: m.index + m[0].length,
          context: contextOf(line, m.index), wholeLine: line.trim() === m[0] });
      }
    });
    return out;
  }
  function summary(text) {
    var order = [], info = {};
    findFields(text).forEach(function (o) {
      if (!info[o.key]) { order.push(o.key); info[o.key] = { name: o.name, key: o.key, count: 0, contexts: [] }; }
      info[o.key].count++;
      if (info[o.key].contexts.indexOf(o.context) === -1) info[o.key].contexts.push(o.context);
    });
    return order.map(function (k) { return info[k]; });
  }
  function parseValues(values) {
    var plain = {}, ctx = {}, nth = {};
    Object.keys(values).forEach(function (raw) {
      var v = values[raw];
      if (v == null || !String(v).trim()) return;
      v = String(v);
      var k = raw.trim(), m = k.match(/^(.*)#(\d+)$/);
      if (m) { nth[normName(m[1]) + "#" + m[2]] = v; return; }
      var at = k.lastIndexOf("@");
      if (at !== -1) { var c = k.slice(at + 1); ctx[normName(k.slice(0, at)) + "@" + (c === "^" ? "" : c).toLowerCase()] = v; return; }
      plain[normName(k)] = v;
    });
    return { plain: plain, ctx: ctx, nth: nth };
  }
  // Returns {text, spans}: spans marks filled ranges per line for highlighting.
  function fill(text, values) {
    var p = parseValues(values);
    var lines = text.split("\n");
    var byLine = {};
    findFields(text).forEach(function (o) { (byLine[o.line] = byLine[o.line] || []).push(o); });
    var filledMarks = {};
    Object.keys(byLine).forEach(function (ln) {
      var line = lines[ln], marks = [];
      byLine[ln].sort(function (a, b) { return b.start - a.start; }).forEach(function (o) {
        var v = p.nth[o.key + "#" + o.occurrence];
        if (v == null) v = p.ctx[o.key + "@" + o.context.toLowerCase()];
        if (v == null) v = p.plain[o.key];
        if (v == null) return;
        if (!o.wholeLine) v = v.split(/\r?\n/).map(function (s) { return s.trim(); }).filter(Boolean).join(", ");
        line = line.slice(0, o.start) + v + line.slice(o.end);
        marks.forEach(function (mk) { mk.start += v.length - (o.end - o.start); mk.end += v.length - (o.end - o.start); });
        marks.push({ start: o.start, end: o.start + v.length });
      });
      lines[ln] = line;
      filledMarks[ln] = marks;
    });
    return { text: lines.join("\n"), marks: filledMarks };
  }
  function unresolved(text) {
    var counts = {}, order = [];
    findFields(text).forEach(function (o) { if (!(o.name in counts)) { counts[o.name] = 0; order.push(o.name); } counts[o.name]++; });
    return order.map(function (n) { return { name: n, count: counts[n] }; });
  }

  // ------------------------------------------------------------------ rendering
  function inline(line, marks) {
    // Highlight remaining [fields] and filled values.
    var frag = document.createDocumentFragment();
    var ranges = [];
    (marks || []).forEach(function (m) { ranges.push({ s: m.start, e: m.end, ok: true }); });
    var m; FIELD_RE.lastIndex = 0;
    while ((m = FIELD_RE.exec(line))) {
      var s = m.index, e = s + m[0].length;
      var inside = ranges.some(function (r) { return r.ok && s >= r.s && e <= r.e; });
      if (!inside) ranges.push({ s: s, e: e, ok: false });
    }
    ranges.sort(function (a, b) { return a.s - b.s; });
    var pos = 0;
    ranges.forEach(function (r) {
      if (r.s < pos) return;
      if (r.s > pos) frag.appendChild(document.createTextNode(line.slice(pos, r.s)));
      frag.appendChild(el("span", { class: r.ok ? "fld ok" : "fld", text: line.slice(r.s, r.e) }));
      pos = r.e;
    });
    if (pos < line.length) frag.appendChild(document.createTextNode(line.slice(pos)));
    return frag;
  }
  function stripHash(line) { return line.replace(/^#{1,2} /, ""); }
  function shift(marks, n) { return (marks || []).map(function (m) { return { start: m.start - n, end: m.end - n }; }); }

  function renderDoc(container, text, layout, marks) {
    container.textContent = "";
    var court = layout === "COURT" || layout === "APPELLATE" || layout === "APPELLATE_PAPER";
    var wrap = el("div", { class: court ? "dbl" : "" });
    var lines = text.split("\n");
    var section = layout === "APPELLATE" ? "cover" : "body";
    for (var i = 0; i < lines.length; i++) {
      var line = lines[i], mk = marks ? marks[i] : null;
      var t = line.trim();
      if (!t) continue;
      if (/^<!--\s*(pagebreak|frontmatter|body)\s*-->$/.test(t)) {
        var kind = t.replace(/<!--\s*|\s*-->/g, "");
        if (kind !== "pagebreak") section = kind;
        wrap.appendChild(el("hr", { class: "marker" }));
        wrap.appendChild(el("span", { class: "marker-label", text: kind === "pagebreak" ? "Page break" : kind === "frontmatter" ? "Front matter (roman page numbers)" : "Body (arabic page numbers)" }));
        continue;
      }
      if (court && line.indexOf("|") !== -1) {
        var table = el("table", { class: "caption" });
        var tb = el("tbody");
        while (i < lines.length && lines[i].indexOf("|") !== -1) {
          var row = lines[i], cut = row.indexOf("|");
          var rm = marks ? marks[i] : null;
          var left = row.slice(0, cut), right = row.slice(cut + 1);
          var lTrim = left.length - left.replace(/^\s+/, "").length;
          var rOff = cut + 1 + (right.length - right.replace(/^\s+/, "").length);
          var tdL = el("td"), tdM = el("td", { class: "mid", text: ")" }), tdR = el("td");
          tdL.appendChild(inline(left.trim(), shift((rm || []).filter(function (m) { return m.end <= cut; }), lTrim)));
          tdR.appendChild(inline(right.trim(), shift((rm || []).filter(function (m) { return m.start > cut; }), rOff)));
          tb.appendChild(el("tr", null, [tdL, tdM, tdR]));
          i++;
        }
        i--;
        table.appendChild(tb);
        wrap.appendChild(table);
        continue;
      }
      var p;
      if (/^# /.test(line)) {
        p = el("p", { class: "ttl" }); p.appendChild(inline(stripHash(line), shift(mk, 2)));
      } else if (/^## /.test(line)) {
        p = el("p", { class: "hd" }); p.appendChild(inline(stripHash(line), shift(mk, 3)));
      } else {
        var num = line.match(/^(\d+)\. (.*)$/);
        if (num) {
          var off = num[1].length + 2;
          var txt = el("span"); txt.appendChild(inline(num[2], shift(mk, off)));
          p = el("p", { class: "num" }, [el("span", { text: num[1] + "." }), txt]);
        } else {
          p = el("p", { class: section === "cover" ? "center" : "" });
          p.appendChild(inline(line, mk));
        }
      }
      wrap.appendChild(p);
    }
    container.appendChild(wrap);
  }

  // ------------------------------------------------------------------ list
  function courtLabel(t) { return t.court; }
  function buildFilters() {
    var cat = $("f-cat"), lay = $("f-layout"), crt = $("f-court");
    DATA.categories.forEach(function (c) { cat.appendChild(el("option", { value: c.id, text: c.label })); });
    Object.keys(LAYOUTS).forEach(function (k) { lay.appendChild(el("option", { value: k, text: LAYOUTS[k] })); });
    var courts = [];
    DATA.templates.forEach(function (t) { if (courts.indexOf(t.court) === -1) courts.push(t.court); });
    courts.sort().forEach(function (c) { crt.appendChild(el("option", { value: c, text: c })); });
  }
  function matches(t, words) {
    var hay = (t.title + " " + t.command + " " + t.scope + " " + t.category_label + " " + t.court).toLowerCase();
    return words.every(function (w) { return hay.indexOf(w) !== -1; });
  }
  function renderList() {
    var words = $("q").value.toLowerCase().split(/\s+/).filter(Boolean);
    var cat = $("f-cat").value, lay = $("f-layout").value, crt = $("f-court").value;
    var list = $("list");
    list.textContent = "";
    var shown = 0, lastCat = null;
    DATA.templates.forEach(function (t) {
      if (cat && t.category !== cat) return;
      if (lay && t.layout !== lay) return;
      if (crt && courtLabel(t) !== crt) return;
      if (!matches(t, words)) return;
      if (t.category !== lastCat) {
        list.appendChild(el("li", { class: "group", text: t.category_label }));
        lastCat = t.category;
      }
      var btn = el("button", { type: "button", class: "item", "data-slug": t.slug }, [
        el("span", { class: "t", text: t.title }),
        el("span", { class: "s" }, [el("code", { text: t.command }), el("span", { class: "chip", text: t.layout }), el("span", { text: t.pages + (t.pages === 1 ? " page" : " pages") })])
      ]);
      if (state.current && state.current.slug === t.slug) btn.setAttribute("aria-current", "true");
      btn.addEventListener("click", function () { location.hash = "#/t/" + t.slug; });
      list.appendChild(el("li", null, [btn]));
      shown++;
    });
    $("result-count").textContent = shown + " of " + DATA.templates.length + " templates";
    if (!shown) list.appendChild(el("li", { class: "group", text: "No templates match. Try fewer words or clear a filter." }));
  }

  // ------------------------------------------------------------------ detail
  function show(slug) {
    var t = DATA.templates.filter(function (x) { return x.slug === slug; })[0];
    if (!t) { $("doc").hidden = true; $("empty").hidden = false; state.current = null; renderList(); return; }
    state.current = t;
    state.values = {};
    $("empty").hidden = true;
    $("doc").hidden = false;
    $("d-cat").textContent = t.category_label;
    $("d-title").textContent = t.title;
    $("d-cmd").textContent = t.command;
    $("d-court").textContent = t.court;
    $("d-layout").textContent = LAYOUTS[t.layout] || t.layout;
    $("d-pages").textContent = String(t.pages);
    $("d-scope").textContent = t.scope;
    $("d-docx").setAttribute("href", "docx/" + t.slug + ".docx");
    $("d-docx").setAttribute("download", t.slug + ".docx");
    $("d-reason").setAttribute("href", REPO_URL + t.reasoning_path);
    renderDoc($("preview"), body(t), t.layout, null);
    buildForm(t);
    selectPane("preview");
    renderList();
    document.title = t.title + " · Virginia PI Templates";
    if (window.matchMedia("(max-width: 899px)").matches) $("detail").scrollIntoView({ block: "start" });
  }
  function selectPane(which) {
    var prev = which === "preview";
    $("st-preview").setAttribute("aria-selected", String(prev));
    $("st-fill").setAttribute("aria-selected", String(!prev));
    $("pane-preview").hidden = !prev;
    $("pane-fill").hidden = prev;
  }
  function inputFor(id, label, name) {
    var long = name.length > 32 || /FACTS|DESCRIPTION|SUMMARY|ADDRESSES|ARGUMENT|LIST|REASONS|STATEMENT/.test(name);
    var input = long ? el("textarea", { id: id, rows: "2" }) : el("input", { id: id, type: "text" });
    return input;
  }
  function buildForm(t) {
    var form = $("fill-form");
    form.textContent = "";
    var fields = summary(body(t));
    $("field-count").textContent = String(fields.length);
    fields.forEach(function (f, n) {
      var id = "fv-" + n;
      var box = el("div", { class: "fieldset" });
      box.appendChild(el("label", { for: id }, [f.name + " ", el("span", { class: "count", text: f.count > 1 ? "×" + f.count : "" })]));
      var input = inputFor(id, f.name, f.name);
      input.addEventListener("input", function () { state.values[f.name] = input.value; refresh(); });
      box.appendChild(input);
      if (f.contexts.length > 1) {
        var det = el("details", null, [el("summary", { text: "Different values by place (" + f.contexts.length + ")" })]);
        var ctxBox = el("div", { class: "ctx" });
        f.contexts.forEach(function (c, j) {
          var cid = id + "-" + j, key = f.name + "@" + (c || "^");
          ctxBox.appendChild(el("label", { for: cid, text: c ? "After “" + c + "”" : "At the start of a line" }));
          var ci = el("input", { id: cid, type: "text", placeholder: "Uses the main value if empty" });
          ci.addEventListener("input", function () { state.values[key] = ci.value; refresh(); });
          ctxBox.appendChild(ci);
        });
        det.appendChild(ctxBox);
        box.appendChild(det);
      }
      form.appendChild(box);
    });
    refresh();
  }
  function filledText() { return fill(body(state.current), state.values); }
  function refresh() {
    if (!state.current) return;
    var res = filledText();
    renderDoc($("filled"), res.text, state.current.layout, res.marks);
    var left = unresolved(res.text);
    var u = $("unresolved");
    u.textContent = "";
    if (!left.length) { u.appendChild(el("p", { text: "All bracketed fields are filled. Review every value against the case file before use." })); return; }
    u.appendChild(el("p", null, [el("strong", { text: left.length + " field" + (left.length === 1 ? "" : "s") + " still bracketed" }), " (left for attorney completion):"]));
    var ul = el("ul");
    left.forEach(function (f) { ul.appendChild(el("li", { text: "[" + f.name + "]" + (f.count > 1 ? " ×" + f.count : "") })); });
    u.appendChild(ul);
  }

  // ------------------------------------------------------------------ actions
  function toast(msg) {
    var t = $("toast");
    t.textContent = msg;
    t.classList.add("show");
    clearTimeout(toast._h);
    toast._h = setTimeout(function () { t.classList.remove("show"); }, 1800);
  }
  function download(name, text) {
    var blob = new Blob([text], { type: "text/markdown;charset=utf-8" });
    var url = URL.createObjectURL(blob);
    var a = el("a", { href: url, download: name });
    document.body.appendChild(a);
    a.click();
    setTimeout(function () { URL.revokeObjectURL(url); a.remove(); }, 0);
  }
  function copy(text) {
    function fallback() {
      var ta = el("textarea");
      ta.value = text;
      ta.setAttribute("readonly", "");
      ta.style.position = "fixed"; ta.style.opacity = "0";
      document.body.appendChild(ta);
      ta.select();
      var ok = false;
      try { ok = document.execCommand("copy"); } catch (e) { ok = false; }
      ta.remove();
      toast(ok ? "Copied" : "Copy failed; select the text manually");
    }
    if (navigator.clipboard && window.isSecureContext) {
      navigator.clipboard.writeText(text).then(function () { toast("Copied"); }, fallback);
    } else fallback();
  }

  // ------------------------------------------------------------------ routes view
  function renderRoutes() {
    var words = $("rq").value.toLowerCase().split(/\s+/).filter(Boolean);
    var box = $("routes");
    box.textContent = "";
    var order = ["official-form", "official-process", "clerk-process", "specialist", "choose-template", "alias", "not-included"];
    order.forEach(function (kind) {
      var items = DATA.routes.filter(function (r) {
        if (r.kind !== kind) return false;
        var hay = (r.command + " " + r.title + " " + r.what_to_do + " " + (r.form_id || "")).toLowerCase();
        return words.every(function (w) { return hay.indexOf(w) !== -1; });
      });
      if (!items.length) return;
      box.appendChild(el("h3", { text: items[0].kind_label + " (" + items.length + ")" }));
      items.forEach(function (r) {
        var links = el("p");
        if (r.official_link) links.appendChild(el("a", { href: r.official_link, rel: "noopener", text: "Official source" }));
        if (r.reasoning) {
          if (links.childNodes.length) links.appendChild(document.createTextNode(" · "));
          links.appendChild(el("a", { href: REPO_URL + r.reasoning, rel: "noopener", text: "Reasoning" }));
        }
        if (r.alias_of) {
          var target = r.alias_of.slice(1);
          if (DATA.templates.some(function (t) { return t.slug === target; })) {
            if (links.childNodes.length) links.appendChild(document.createTextNode(" · "));
            links.appendChild(el("a", { href: "#/t/" + target, text: "Open " + r.alias_of }));
          }
        }
        box.appendChild(el("div", { class: "route" }, [
          el("div", { class: "rt" }, [el("code", { text: r.command }), el("strong", { text: r.title + (r.form_id ? " (" + r.form_id + ")" : "") })]),
          el("p", { text: r.what_to_do }),
          links.childNodes.length ? links : null
        ]));
      });
    });
    if (!box.childNodes.length) box.appendChild(el("p", { class: "muted", text: "No routes match." }));
  }

  // ------------------------------------------------------------------ views + routing
  function setView(view) {
    ["templates", "routes", "about"].forEach(function (v) {
      $("view-" + v).hidden = v !== view;
      document.querySelector('.tab[data-view="' + v + '"]').setAttribute("aria-pressed", String(v === view));
    });
  }
  function route() {
    var h = location.hash || "";
    var m = h.match(/^#\/t\/([\w-]+)$/);
    if (m) { setView("templates"); show(m[1]); return; }
    if (h === "#/routes") { setView("routes"); return; }
    if (h === "#/about") { setView("about"); return; }
    setView("templates");
  }

  function init() {
    $("count").textContent = String(DATA.templates.length);
    $("asof").textContent = DATA.dataAsOf || "";
    buildFilters();
    renderList();
    renderRoutes();
    ["q", "f-cat", "f-layout", "f-court"].forEach(function (id) { $(id).addEventListener("input", renderList); });
    $("rq").addEventListener("input", renderRoutes);
    Array.prototype.forEach.call(document.querySelectorAll(".tab"), function (b) {
      b.addEventListener("click", function () {
        var v = b.getAttribute("data-view");
        if (v === "templates") location.hash = state.current ? "#/t/" + state.current.slug : "#/";
        else location.hash = "#/" + v;
      });
    });
    $("st-preview").addEventListener("click", function () { selectPane("preview"); });
    $("st-fill").addEventListener("click", function () { selectPane("fill"); });
    $("back").addEventListener("click", function () { $("q").focus(); $("list").scrollIntoView({ block: "start" }); });
    $("d-md").addEventListener("click", function () { if (state.current) download(state.current.slug + ".md", state.current.md); });
    $("d-copy").addEventListener("click", function () { if (state.current) copy(body(state.current)); });
    $("f-copy").addEventListener("click", function () { if (state.current) copy(filledText().text); });
    $("f-download").addEventListener("click", function () { if (state.current) download(state.current.slug + "-filled.md", filledText().text); });
    $("f-clear").addEventListener("click", function () { if (state.current) { buildFormReset(); } });
    window.addEventListener("hashchange", route);
    route();
  }
  function buildFormReset() { state.values = {}; buildForm(state.current); toast("Cleared"); }

  // Exposed for quick checks in the browser console.
  window.VPT = { fill: fill, findFields: findFields, summary: summary, unresolved: unresolved };
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", init); else init();
})();
