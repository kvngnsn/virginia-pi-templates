#!/usr/bin/env python3
"""Regenerate the template index and the static site data from templates/.

Outputs (all derived; edit the templates and templates/routes.json instead):
  templates/INDEX.md     human index of drafting templates
  templates/ROUTES.md    entries that are official forms, clerk/agency processes,
                         specialist work, procedure choices or aliases (no drafts)
  docs/templates.json    machine index (metadata only)
  docs/routes.json       copy of templates/routes.json
  docs/data.js           everything the browser app needs, including template text
  docs/docx/*.docx       byte copies of the reviewed Word files for download

Run:  python3 scripts/build_index.py          (write)
      python3 scripts/build_index.py --check  (exit 1 if anything is stale)
Standard library only.
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from fill_template import field_summary, parse_front_matter  # noqa: E402

DATA_AS_OF = "2026-09-21"
CATEGORY_ORDER = [
    "client", "investigation", "insurance", "medical", "liens", "demand", "settlement",
    "pleadings", "discovery", "motions", "trial", "post-trial-appeals",
]
LAYOUT_NOTE = {
    "COURT": "court paper",
    "LETTER": "letter",
    "DOCUMENT": "plain document",
    "APPELLATE": "appellate brief",
    "APPELLATE_PAPER": "appellate paper",
}
KIND_ORDER = ["official-form", "official-process", "clerk-process", "specialist", "choose-template", "alias", "not-included"]


def load_templates():
    rows = []
    for path in sorted((ROOT / "templates").glob("*/*.md")):
        raw = path.read_text(encoding="utf-8")
        meta, body = parse_front_matter(raw)
        if not meta:
            continue
        rel = path.relative_to(ROOT).as_posix()
        folder = path.parent.relative_to(ROOT).as_posix()
        meta = dict(meta)
        meta["path"] = rel
        meta["docx_path"] = f"{folder}/{meta['docx']}"
        meta["reasoning_path"] = f"reasoning/{meta['slug']}.md"
        meta["field_count"] = len(field_summary(body))
        meta["_raw"] = raw
        rows.append((meta, body))
    rows.sort(key=lambda r: (CATEGORY_ORDER.index(r[0]["category"]), r[0]["title"].casefold()))
    return rows


def esc(s):
    return str(s).replace("|", "\\|")


def index_md(rows):
    total_pages = sum(m["pages"] for m, _ in rows)
    out = [
        "# Template index",
        "",
        f"{len(rows)} Virginia personal-injury drafting templates ({total_pages} blank pages). "
        f"Text and reasoning as of the source snapshot verified {DATA_AS_OF}. "
        "Drafts for attorney review only; not legal advice. Official forms, clerk-issued process, "
        "specialist work and procedure choices are listed separately in [ROUTES.md](ROUTES.md), with no drafts.",
        "",
        "Layout profiles are explained in [references/layout-profiles.md](../references/layout-profiles.md). "
        "This file is generated by `scripts/build_index.py`.",
        "",
    ]
    by_cat = {}
    for meta, _ in rows:
        by_cat.setdefault(meta["category"], []).append(meta)
    for cat in CATEGORY_ORDER:
        items = by_cat.get(cat, [])
        if not items:
            continue
        out += [f"## {items[0]['category_label']} ({len(items)})", "",
                "| Template | Command | Court / scope | Layout | Pages | Files |",
                "|---|---|---|---|---:|---|"]
        for m in items:
            base = m["path"].split("/", 1)[1]
            docx = m["docx_path"].split("/", 1)[1]
            out.append(
                f"| {esc(m['title'])} | `{m['command']}` | {esc(m['court'])} | {m['layout']} | {m['pages']} | "
                f"[md]({base}) · [docx]({docx}) · [reasoning](../{m['reasoning_path']}) |"
            )
        out.append("")
    return "\n".join(out)


def routes_md(routes):
    labels = {}
    for r in routes:
        labels.setdefault(r["kind"], r["kind_label"])
    out = [
        "# Routes without drafts",
        "",
        f"{len(routes)} catalog entries that are deliberately **not** drafting templates. Each says what to use instead. "
        "No substitute drafts were written for these. Official form numbers and links come from the source snapshot "
        f"({DATA_AS_OF}); verify the current form, edition and procedure with the publisher. Generated by `scripts/build_index.py`.",
        "",
    ]
    for kind in KIND_ORDER:
        items = [r for r in routes if r["kind"] == kind]
        if not items:
            continue
        out += [f"## {labels[kind]} ({len(items)})", "", "| Command | Entry | What to do | Links |", "|---|---|---|---|"]
        for r in sorted(items, key=lambda x: x["command"]):
            links = []
            if r.get("official_link"):
                links.append(f"[official source]({r['official_link']})")
            if r.get("reasoning"):
                links.append(f"[reasoning](../{r['reasoning']})")
            title = r["title"] + (f" ({r['form_id']})" if r.get("form_id") else "")
            out.append(f"| `{r['command']}` | {esc(title)} | {esc(r['what_to_do'])} | {' · '.join(links)} |")
        out.append("")
    return "\n".join(out)


def site_payload(rows, routes):
    categories = []
    seen = set()
    for meta, _ in rows:
        if meta["category"] not in seen:
            seen.add(meta["category"])
            categories.append({"id": meta["category"], "label": meta["category_label"]})
    index = {
        "data_as_of": DATA_AS_OF,
        "count": len(rows),
        "categories": categories,
        "templates": [{k: v for k, v in m.items() if k != "_raw"} for m, _ in rows],
    }
    data = {
        "dataAsOf": DATA_AS_OF,
        "categories": categories,
        "templates": [dict({k: v for k, v in m.items() if k != "_raw"}, md=m["_raw"]) for m, _ in rows],
        "routes": routes,
    }
    return index, data


def planned_outputs():
    rows = load_templates()
    routes = json.loads((ROOT / "templates" / "routes.json").read_text(encoding="utf-8"))
    index, data = site_payload(rows, routes)
    files = {
        ROOT / "templates" / "INDEX.md": (index_md(rows) + "\n").encode("utf-8"),
        ROOT / "templates" / "ROUTES.md": (routes_md(routes) + "\n").encode("utf-8"),
        ROOT / "docs" / "templates.json": (json.dumps(index, indent=1, ensure_ascii=False) + "\n").encode("utf-8"),
        ROOT / "docs" / "routes.json": (json.dumps(routes, indent=1, ensure_ascii=False) + "\n").encode("utf-8"),
        ROOT / "docs" / "data.js": (
            "// Generated by scripts/build_index.py. Template data for the offline browser; loaded with a script tag, no network calls.\n"
            "window.VPT_DATA = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n"
        ).encode("utf-8"),
    }
    for meta, _ in rows:
        src = ROOT / meta["docx_path"]
        files[ROOT / "docs" / "docx" / f"{meta['slug']}.docx"] = src.read_bytes()
    return files


def main(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="report stale outputs and exit 1")
    args = parser.parse_args(argv)
    files = planned_outputs()
    stale = [p for p, data in files.items() if not p.exists() or p.read_bytes() != data]
    expected_docx = {p.name for p in files if p.parent.name == "docx" and p.parent.parent.name == "docs"}
    extra = [p for p in (ROOT / "docs" / "docx").glob("*.docx") if p.name not in expected_docx] if (ROOT / "docs" / "docx").exists() else []
    if args.check:
        for p in stale:
            print("stale:", p.relative_to(ROOT))
        for p in extra:
            print("unexpected:", p.relative_to(ROOT))
        return 1 if stale or extra else 0
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(files[p])
    for p in extra:
        p.unlink()
    print(f"wrote {len(stale)} file(s); removed {len(extra)}; {len(files)} outputs up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
